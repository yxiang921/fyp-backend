-- FRMS: clean PostgreSQL reset schema (Laravel-compatible names, Python face recognition included).
-- WARNING: this destroys every object and every record in the target database's public schema.
-- Run ONLY against the new/development FRMS database:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f full_schema.sql

DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
GRANT ALL ON SCHEMA public TO CURRENT_USER;

CREATE TYPE user_role AS ENUM ('super_admin', 'pdrm_officer', 'patrol_unit', 'public_user');
CREATE TYPE missing_person_status AS ENUM ('pending', 'active', 'found', 'closed', 'reopened');
CREATE TYPE camera_status AS ENUM ('online', 'offline', 'maintenance', 'error');
CREATE TYPE camera_stream_type AS ENUM ('mjpeg', 'snapshot', 'rtsp', 'hls', 'custom', 'webcam');
CREATE TYPE detection_status AS ENUM ('new', 'reviewed', 'confirmed', 'rejected', 'false_positive');
CREATE TYPE alert_status AS ENUM ('new', 'under_review', 'escalated', 'closed', 'false_positive');
CREATE TYPE alert_priority AS ENUM ('low', 'medium', 'high', 'critical');
CREATE TYPE verification_status AS ENUM ('pending', 'confirmed', 'rejected', 'insufficient_data');

-- 1. Authentication and role-based access control.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    email_verified_at TIMESTAMPTZ,
    password VARCHAR(255) NOT NULL,
    role user_role NOT NULL DEFAULT 'public_user',
    agency VARCHAR(255),
    phone VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    remember_token VARCHAR(100),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

-- 2. Missing-person case management.
CREATE TABLE missing_persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    gender VARCHAR(30),
    dob DATE,
    national_id VARCHAR(50),
    description TEXT,
    last_seen_location TEXT NOT NULL,
    last_seen_date TIMESTAMPTZ,
    status missing_person_status NOT NULL DEFAULT 'pending',
    created_by BIGINT NOT NULL REFERENCES users(id),
    verified_by BIGINT REFERENCES users(id),
    verified_at TIMESTAMPTZ,
    found_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

-- 3-4. Reference photos and per-case activity history.
CREATE TABLE missing_person_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    missing_person_id BIGINT NOT NULL REFERENCES missing_persons(id) ON DELETE CASCADE,
    path VARCHAR(500) NOT NULL,
    type VARCHAR(50) NOT NULL DEFAULT 'reference',
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    uploaded_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX missing_person_one_primary_photo_idx ON missing_person_photos (missing_person_id) WHERE is_primary;
CREATE TABLE missing_person_timeline (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    missing_person_id BIGINT NOT NULL REFERENCES missing_persons(id) ON DELETE CASCADE,
    event_type VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    recorded_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ
);

-- 5. Camera inventory. Password is retained only for compatibility with the existing camera reader;
-- encrypt it at rest through application/database encryption in production.
CREATE TABLE cameras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    location TEXT,
    ip_address VARCHAR(100),
    port INTEGER CHECK (port IS NULL OR port BETWEEN 1 AND 65535),
    stream_url TEXT,
    stream_type camera_stream_type NOT NULL DEFAULT 'rtsp',
    username VARCHAR(255),
    password TEXT,
    latitude NUMERIC(10,7),
    longitude NUMERIC(10,7),
    status camera_status NOT NULL DEFAULT 'offline',
    description TEXT,
    registered_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

-- 6. Python recognition profiles (the existing completed recognition feature).
CREATE TABLE face_profiles (
    external_id VARCHAR(100) PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    age SMALLINT,
    gender VARCHAR(50),
    notes TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE face_embeddings (
    external_id VARCHAR(100) PRIMARY KEY REFERENCES face_profiles(external_id) ON DELETE CASCADE,
    embedding BYTEA NOT NULL,
    dimensions SMALLINT NOT NULL DEFAULT 512 CHECK (dimensions > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 7-9. Recognition detection, operational alert, and their immutable histories.
CREATE TABLE detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detection_id VARCHAR(50) NOT NULL UNIQUE,
    camera_id BIGINT NOT NULL REFERENCES cameras(id),
    captured_image VARCHAR(500),
    reference_type VARCHAR(100) NOT NULL DEFAULT 'missing_person',
    reference_id BIGINT NOT NULL REFERENCES missing_persons(id),
    similarity_score NUMERIC(5,2) NOT NULL CHECK (similarity_score BETWEEN 0 AND 100),
    status detection_status NOT NULL DEFAULT 'new',
    detected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_by BIGINT REFERENCES users(id),
    review_notes TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id VARCHAR(50) NOT NULL UNIQUE,
    detection_id BIGINT NOT NULL UNIQUE REFERENCES detections(id) ON DELETE CASCADE,
    missing_person_id BIGINT NOT NULL REFERENCES missing_persons(id),
    title VARCHAR(255) NOT NULL,
    message TEXT,
    location TEXT,
    status alert_status NOT NULL DEFAULT 'new',
    priority alert_priority NOT NULL DEFAULT 'high',
    assigned_to BIGINT REFERENCES users(id),
    assigned_at TIMESTAMPTZ,
    resolved_by BIGINT REFERENCES users(id),
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE TABLE alert_timeline (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT NOT NULL REFERENCES alerts(id) ON DELETE CASCADE,
    event_type VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    performed_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ
);

-- 10-11. Formal JPN/PDRM verification requests and their supporting documents.
CREATE TABLE verification_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(50) NOT NULL UNIQUE,
    detection_id BIGINT NOT NULL UNIQUE REFERENCES detections(id) ON DELETE CASCADE,
    alert_id BIGINT NOT NULL UNIQUE REFERENCES alerts(id) ON DELETE CASCADE,
    requested_by BIGINT NOT NULL REFERENCES users(id),
    reviewed_by BIGINT REFERENCES users(id),
    status verification_status NOT NULL DEFAULT 'pending',
    jpn_notes TEXT,
    police_notes TEXT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE TABLE verification_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verification_request_id BIGINT NOT NULL REFERENCES verification_requests(id) ON DELETE CASCADE,
    path VARCHAR(500) NOT NULL,
    type VARCHAR(100) NOT NULL,
    uploaded_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

-- 12-13. User notifications, full audit trail, and configurable system settings.
CREATE TABLE notifications (
    id UUID PRIMARY KEY,
    type VARCHAR(255) NOT NULL,
    notifiable_type VARCHAR(255) NOT NULL,
    notifiable_id BIGINT NOT NULL,
    data JSONB NOT NULL,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    module VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    old_values JSONB,
    new_values JSONB,
    ip_address INET,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE email_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT REFERENCES alerts(id) ON DELETE SET NULL,
    recipient_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    recipient_email VARCHAR(255),
    subject VARCHAR(500) NOT NULL,
    body TEXT NOT NULL,
    source VARCHAR(30) NOT NULL CHECK (source IN ('automatic', 'manual')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('sent', 'failed')),
    error_message TEXT,
    sent_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE system_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(100) NOT NULL UNIQUE,
    value TEXT,
    type VARCHAR(20) NOT NULL DEFAULT 'string' CHECK (type IN ('string','boolean','integer','json')),
    description TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE INDEX missing_persons_status_idx ON missing_persons(status);
CREATE INDEX missing_persons_created_by_idx ON missing_persons(created_by);
CREATE INDEX cameras_status_idx ON cameras(status);
CREATE INDEX detections_camera_detected_idx ON detections(camera_id, detected_at DESC);
CREATE INDEX detections_reference_idx ON detections(reference_type, reference_id);
CREATE INDEX alerts_assignee_status_idx ON alerts(assigned_to, status, created_at DESC);
CREATE INDEX notifications_notifiable_read_idx ON notifications(notifiable_type, notifiable_id, read_at);
CREATE INDEX audit_logs_module_created_idx ON audit_logs(module, created_at DESC);
CREATE INDEX email_logs_created_at_idx ON email_logs(created_at DESC);
CREATE INDEX email_logs_alert_id_idx ON email_logs(alert_id);
CREATE INDEX face_profiles_name_idx ON face_profiles(full_name);

