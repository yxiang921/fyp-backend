-- Run once against an existing FRMS PostgreSQL database.
CREATE TABLE IF NOT EXISTS email_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT REFERENCES alerts(id) ON DELETE SET NULL,
    recipient_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    recipient_email VARCHAR(255),
    subject VARCHAR(500) NOT NULL,
    body TEXT NOT NULL,
    source VARCHAR(30) NOT NULL CHECK (source IN ('automatic', 'manual')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('sent', 'failed')),
    error_message TEXT,
    sent_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS email_logs_created_at_idx ON email_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS email_logs_alert_id_idx ON email_logs (alert_id);
